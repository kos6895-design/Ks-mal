import fs from 'node:fs';
const p='worker-direct.js';
let s=fs.readFileSync(p,'utf8');
const start=s.indexOf('<script>(()=>{const f=document.querySelector');
if(start<0)throw Error('autosave script start missing');
const end=s.indexOf('</script>',start);
if(end<0)throw Error('autosave script end missing');
s=s.slice(0,start)+s.slice(end+9);
const marker='<span id="autosaveState" class="muted">Автосохранение включено</span>';
if(!s.includes(marker))throw Error('save state marker missing');
s=s.replace(marker,'<button class="btn primary" type="submit">Сохранить смену</button><span class="muted">После изменения данных нажмите «Сохранить смену»</span>');
if(s.includes('autosaveState')||s.includes('X-Autosave')&&s.includes('<script>(()=>{const f=document.querySelector'))throw Error('autosave UI removal incomplete');
fs.writeFileSync(p,s);
console.log('Manual current-shift save button added');
